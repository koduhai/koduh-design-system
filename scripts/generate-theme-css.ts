import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens, themes, density } from '../src/theme/tokens';

const camelToKebab = (s: string) =>
  s
    // camelCase boundary: lower/digit → Upper (bgDefault → bg-default)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    // letter → digit boundary: keeps numbered scales readable (chart1 → chart-1)
    .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
    .toLowerCase();

function scaleVars(): string {
  const lines: string[] = [];
  for (const [scaleName, scale] of Object.entries(tokens)) {
    for (const [key, value] of Object.entries(scale)) {
      lines.push(`  --ku-${camelToKebab(scaleName)}-${camelToKebab(String(key))}: ${value};`);
    }
  }
  return lines.join('\n');
}

function colorVars(mode: 'dark' | 'light'): string {
  return Object.entries(themes[mode].color)
    .map(([name, value]) => `  --ku-color-${camelToKebab(name)}: ${value};`)
    .join('\n');
}

// Back-compat aliases for v1 colour tokens renamed in v2 (#47). Consuming CSS
// that still references the old name (with no fallback) would otherwise produce
// an invalid declaration that silently renders as nothing. Each alias delegates
// to its replacement via var(), so it resolves correctly under every theme.
// DEPRECATED — slated for removal in the next major; migrate to the replacement.
const deprecatedColorAliases: Record<string, string> = {
  'bg-subtle': 'bg-surface',
  'border-default': 'border',
  'fg-default': 'text-primary',
};

function aliasVars(): string {
  const lines = ['  /* Deprecated v1→v2 colour-token aliases (#47) — remove next major. */'];
  for (const [oldName, replacement] of Object.entries(deprecatedColorAliases)) {
    lines.push(`  --ku-color-${oldName}: var(--ku-color-${replacement});`);
  }
  return lines.join('\n');
}

// Density-aware spacing vars. `comfortable` is the default (emitted on :root with
// the scale/color vars); `compact` overrides the same `--ku-density-*` names under
// `[data-density='compact']`. Components read these for internal padding/row-height.
function densityVars(mode: 'comfortable' | 'compact'): string {
  return Object.entries(density[mode])
    .map(([name, value]) => `  --ku-density-${camelToKebab(name)}: ${value};`)
    .join('\n');
}

export function buildThemeCss(): string {
  return [
    '/* AUTO-GENERATED by scripts/generate-theme-css.ts — do not edit by hand. */',
    `:root {\n${scaleVars()}\n${colorVars('dark')}\n${densityVars('comfortable')}\n${aliasVars()}\n}`,
    // Theme overrides respond to BOTH strategies: the `data-theme` attribute
    // (set by KoduhThemeProvider) AND a `.dark` / `.light` class — the latter so
    // Tailwind consumers using `darkMode: 'class'` get our tokens for free. Note
    // :root above is dark-by-default; a class-strategy app whose light state is
    // "no class" must toggle `.light` explicitly to reach the light palette.
    `:root[data-theme='dark'], [data-theme="dark"], :root.dark, .dark {\n${colorVars('dark')}\n}`,
    `:root[data-theme='light'], [data-theme="light"], :root.light, .light {\n${colorVars('light')}\n}`,
    `[data-density='comfortable'] {\n${densityVars('comfortable')}\n}`,
    `[data-density='compact'] {\n${densityVars('compact')}\n}`,
    '',
  ].join('\n\n');
}

// CLI entry: write to dist/theme.css (called by `npm run build:tokens`).
const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../dist');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'theme.css'), buildThemeCss(), 'utf8');
  console.log('Wrote dist/theme.css');
}
